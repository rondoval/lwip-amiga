# Unimplemented LVOs that return POINTERS get the NULL stub; handing an app
# LibStub's -1 where it checks for NULL would be a crash.
NULL_STUBS = {
    "mbuf_copym", "mbuf_free", "mbuf_get", "mbuf_gethdr", "mbuf_prepend",
    "mbuf_pullup", "GetRouteInfo", "ObtainInterfaceList", "ObtainRoadshowData",
}

HEADER = """\
/* SPDX-License-Identifier: BSD-3-Clause */
/*
 * bsdsocket.library LVO vector table — GENERATED by scripts/gen-vectors.py
 * from sfd/bsdsocket_lib.sfd (NDK 3.2R4). Do not edit by hand; regenerate.
 *
 * Implemented LVOs point at their bsd_* functions (see the IMPLEMENTED map
 * in the generator); the rest stay on LibStub. The table length and order
 * are the ABI — apps call by LVO offset.
 */

#include <exec/types.h>

#include "sb_base.h"

const APTR bsdsocket_functable[] = {
    (APTR)LibOpen,    /*   -6 */
    (APTR)LibClose,   /*  -12 */
    (APTR)LibExpunge, /*  -18 */
    (APTR)LibNull,    /*  -24 */
"""

FOOTER = """\
    (APTR)-1};
"""


def main():
    slots = []  # (name, is_reserved)
    varargs_pending = False
    bias = None

    for raw in SFD.read_text(errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("*"):
            continue
        if line.startswith("=="):
            directive = line[2:].split(None, 1)
            key = directive[0].lower()
            if key == "bias":
                bias = int(directive[1])
            elif key == "reserve":
                for _ in range(int(directive[1])):
                    slots.append(("reserved", True))
            elif key == "varargs":
                varargs_pending = True
            continue
        if "(" not in line:
            continue
        head = line.split("(", 1)[0].replace("*", " ").strip()
        name = head.split()[-1]
        if not re.fullmatch(r"[A-Za-z_]\w*", name):
            sys.exit(f"cannot parse function name from: {raw!r}")
        if varargs_pending:
            # varargs alias of the previous slot: C glue only, no LVO
            varargs_pending = False
            continue
        slots.append((name, False))

    if bias != 30:
        sys.exit(f"unexpected ==bias {bias} (expected 30)")

    lines = [HEADER]
    for i, (name, reserved) in enumerate(slots):
        offset = bias + 6 * i
        tag = f"(reserved)" if reserved else name
        default = "LibStubNull" if name in NULL_STUBS else "LibStub"
        sym = "LibStub" if reserved else IMPLEMENTED.get(name, default)
        lines.append(f"    (APTR){sym}, /* -{offset:<4d} {tag} */\n")
    lines.append(FOOTER)
    OUT.write_text("".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(slots)} LVO slots, last at -{bias + 6 * (len(slots) - 1)}")


if __name__ == "__main__":
    main()
