"""Generate the bsdsocket.library LVO vector table from the NDK sfd.

Reads sfd/bsdsocket_lib.sfd and writes src/bsdsocket/vectors.c: the complete
function table in exact LVO order, every slot pointing at LibStub until the
real implementation lands. ==varargs entries are C-glue aliases of the
preceding slot (no LVO of their own); ==reserve N emits N stub slots.

Run manually from the repo root when the sfd changes:
    python3 scripts/gen-vectors.py
The output is checked in, so the Amiga build has no generator dependency.
"""

